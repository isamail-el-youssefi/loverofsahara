/**
 * Repeatable import of the old site's reviews (Supabase "Review" table exported as CSV) into
 * src/data/reviews/reviews.json, the build-time copy of the reviews.
 *
 *   node scripts/import-old-reviews.mjs                  (reads ./Review_rows.csv)
 *   node scripts/import-old-reviews.mjs "<path to Review_rows.csv>"
 *   node scripts/reviews-to-sql.mjs > migrations/seed-old-reviews.sql      (then load it into D1)
 *
 * - Old trips were numbers ("3", "9", "12"); they are mapped to the new trip slugs (src/data/trips/slugs.ts).
 *   An unknown number, or a number whose old `type` doesn't match the trip's category, stops the import.
 * - Personal data is left OUT: email addresses are never copied.
 * - Keeps everything else as exported: the reviewer's language, the owner's reply and the ImageKit photo links.
 */
import fs from "node:fs";
import path from "node:path";

const root = process.cwd();
const source = process.argv[2] ?? path.join(root, "Review_rows.csv");

// old trip number -> new slug (keep in step with src/data/trips/slugs.ts)
const slugsFile = fs.readFileSync(path.join(root, "src", "data", "trips", "slugs.ts"), "utf8");
const SLUG = Object.fromEntries([...slugsFile.matchAll(/^\s+(\d+):\s*"([^"]+)"/gm)].map((m) => [m[1], m[2]]));
// old trip number -> category, from the table generated by `npm run trips:import`
const mapDoc = fs.readFileSync(path.join(root, "docs", "trips-slug-map.md"), "utf8");
const CATEGORY = Object.fromEntries([...mapDoc.matchAll(/^\|\s*(\d+)\s*\|\s*`[^`]+`\s*\|\s*(\w+)\s*\|/gm)].map((m) => [m[1], m[2]]));

/** Small RFC-4180 CSV parser (quoted fields, doubled quotes, newlines inside quotes). */
function parseCsv(text) {
  const rows = [];
  let row = [];
  let field = "";
  let quoted = false;
  for (let i = 0; i < text.length; i++) {
    const c = text[i];
    if (quoted) {
      if (c === '"') {
        if (text[i + 1] === '"') {
          field += '"';
          i++;
        } else quoted = false;
      } else field += c;
    } else if (c === '"') quoted = true;
    else if (c === ",") {
      row.push(field);
      field = "";
    } else if (c === "\n" || c === "\r") {
      if (c === "\r" && text[i + 1] === "\n") i++;
      row.push(field);
      field = "";
      rows.push(row);
      row = [];
    } else field += c;
  }
  if (field || row.length) {
    row.push(field);
    rows.push(row);
  }
  return rows.filter((r) => r.some((v) => v !== ""));
}

const STOP = {
  en: ["the", "and", "was", "with", "our", "very", "for", "this", "had", "we"],
  fr: ["le", "la", "les", "et", "nous", "pour", "avec", "une", "des", "très"],
  de: ["und", "der", "die", "das", "ein", "ist", "wir", "mit", "sehr", "für"],
  it: ["il", "la", "che", "una", "per", "con", "nel", "della", "è", "stata"],
  es: ["el", "los", "las", "una", "con", "por", "muy", "que", "fue", "nuestro"],
};
function lang(text) {
  const words = text.toLowerCase().match(/[\p{L}']+/gu) ?? [];
  let best = "en";
  let top = -1;
  for (const [l, list] of Object.entries(STOP)) {
    const hit = words.filter((w) => list.includes(w)).length;
    if (hit > top) {
      top = hit;
      best = l;
    }
  }
  return best;
}

/** "2026-06-13 15:43:12.93" -> "2026-06-13" */
const day = (s) => (s ?? "").trim().slice(0, 10);

const [header, ...rows] = parseCsv(fs.readFileSync(source, "utf8").replace(/^﻿/, ""));
const kept = [];
for (const cells of rows) {
  const r = Object.fromEntries(header.map((k, i) => [k, cells[i] ?? ""]));
  const slug = SLUG[r.tripId.trim()];
  if (!slug) throw new Error(`Review ${r.id} (${r.fullName}): unknown old trip number "${r.tripId}"`);
  const cat = CATEGORY[r.tripId.trim()];
  if (r.type && cat && r.type !== cat) throw new Error(`Review ${r.id}: old type "${r.type}" but trip ${r.tripId} is a "${cat}"`);
  const photos = (JSON.parse(r.images || "[]") ?? []).filter((u) => /^https:\/\//.test(u));
  const reply = r.adminReply.trim();
  kept.push({
    id: r.id,
    trip: slug,
    name: r.fullName.trim(),
    rating: Number(r.rating),
    comment: r.comment.trim(),
    lang: lang(r.comment),
    date: day(r.createdAt),
    photos,
    ...(reply ? { reply: { text: reply, date: day(r.replyDate) || day(r.createdAt) } } : {}),
  });
}
kept.sort((a, b) => b.date.localeCompare(a.date));

const out = path.join(root, "src", "data", "reviews", "reviews.json");
fs.mkdirSync(path.dirname(out), { recursive: true });
fs.writeFileSync(out, JSON.stringify(kept, null, 2) + "\n");

const perTrip = {};
for (const k of kept) perTrip[k.trip] = (perTrip[k.trip] ?? 0) + 1;
console.log(`reviews.json: ${kept.length} reviews from ${rows.length} CSV rows`);
console.log(Object.entries(perTrip).map(([t, n]) => `  ${t}: ${n}`).join("\n"));
console.log(`photos: ${kept.reduce((n, k) => n + k.photos.length, 0)}, with reply: ${kept.filter((k) => k.reply).length}`);
