import { z } from "zod";

/** Languages the old site shipped. `en` is the source of truth / fallback. */
export const LANGS = ["en", "fr", "de", "es", "it", "zh"] as const;
export type Lang = (typeof LANGS)[number];

export const TRIP_CATEGORIES = ["trip", "excursion", "trekking"] as const;
export type TripCategory = (typeof TRIP_CATEGORIES)[number];

/** Placeholder cover keys; resolved to local assets in `media.ts` until real photos exist. */
export const COVER_KEYS = ["caravan", "dunes", "canyon", "stars", "souk", "atlantic"] as const;
export type CoverKey = (typeof COVER_KEYS)[number];

const slug = z.string().regex(/^[a-z0-9]+(?:-[a-z0-9]+)*$/, "slug must be lowercase kebab-case");

/** One price row. `pricePerPersonPerDay` is EUR, per person, per day, for a group of `persons`. */
export const PricingTierSchema = z.object({
  persons: z.number().int().positive(),
  pricePerPersonPerDay: z.number().positive(),
  days: z.number().int().positive(),
});

export const StopSchema = z.object({
  name: z.string().min(1),
  lat: z.number(),
  lng: z.number(),
});

/** Language-neutral facts about a trip (generated by `scripts/import-old-trips.ts`). */
export const TripMetaSchema = z.object({
  slug,
  /** The number the old site used (1..18). Kept for redirects and the migration table. */
  legacyId: z.number().int().positive(),
  category: z.enum(TRIP_CATEGORIES),
  durationDays: z.number().int().positive(),
  departureCity: z.string().min(1),
  pricing: z.array(PricingTierSchema).min(1),
  stops: z.array(StopSchema),
  /** Route headline per day (the old site hard-coded these in uppercase English). */
  dayRoutes: z.array(z.string()),
  mapEmbedUrl: z.string().url().optional(),
  cover: z.enum(COVER_KEYS),
  /** The trip's card photo on the old site (an ImageKit path, e.g. "/card/7.jpg"). */
  cardImage: z.string().optional(),
});
export type TripMeta = z.infer<typeof TripMetaSchema>;

/**
 * Image paths exactly as the old site referenced them (it served them from ImageKit).
 * Kept in its own file so the UI bundle stays small; used when real photos are wired in.
 */
export const LegacyMediaSchema = z.object({
  carousel: z.array(z.string()),
  days: z.record(z.string(), z.array(z.string())),
});
export const LegacyMediaFileSchema = z.record(z.string(), LegacyMediaSchema);
export type LegacyMedia = z.infer<typeof LegacyMediaSchema>;

export const ItineraryDaySchema = z.object({
  day: z.number().int().positive(),
  text: z.string().min(1),
});

/** English is complete; other languages may omit fields (the loader falls back to English). */
export const TripContentSchema = z.object({
  title: z.string().min(1),
  marketingTitle: z.string().min(1),
  summary: z.string().min(1),
  keyStops: z.array(z.string().min(1)),
  included: z.array(z.string().min(1)).optional(),
  excluded: z.array(z.string().min(1)).optional(),
  itinerary: z.array(ItineraryDaySchema),
});
export type TripContent = z.infer<typeof TripContentSchema>;
export const TripContentPartialSchema = TripContentSchema.partial();
export type TripContentPartial = z.infer<typeof TripContentPartialSchema>;

export const TripsMetaFileSchema = z.array(TripMetaSchema);
export const ContentFileSchema = z.record(z.string(), TripContentPartialSchema);
export const EnglishContentFileSchema = z.record(z.string(), TripContentSchema);
